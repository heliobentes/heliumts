import { randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import type { MethodExport } from "./scanner.js";

export const RPC_MODULE_PATH = "src/rpc.generated.ts";
const RPC_MODULE_HEADER = "// Auto-generated by HeliumTS. Do not edit.";

function generateRpcModule(methods: readonly MethodExport[], root: string): string {
    if (!methods.length) {
        return `${RPC_MODULE_HEADER}\nexport {};\n`;
    }

    const sorted = [...methods].sort((a, b) => a.name.localeCompare(b.name));
    let prefix = "__helium_method_";
    while (sorted.some(({ name }) => name.startsWith(prefix))) {
        prefix = "_" + prefix;
    }
    const imports: string[] = [];
    const references: string[] = [];
    for (const [index, { name, filePath }] of sorted.entries()) {
        const alias = `${prefix}${index}`;
        const relativePath = path.relative(path.join(root, "src"), filePath).split(path.sep).join("/");
        const specifier = JSON.stringify("./" + relativePath);
        imports.push(`import type { ${name} as ${alias} } from ${specifier};`);
        references.push(`export const ${name} = { __id: ${JSON.stringify(name)} } as unknown as import("heliumts/client").MethodReference<
    Parameters<typeof ${alias}["handler"]>[0],
    Awaited<ReturnType<typeof ${alias}["handler"]>>
>;`);
    }
    return `${RPC_MODULE_HEADER}\n/* eslint-disable */\n${imports.join("\n")}\n\n${references.join("\n\n")}\n`;
}

function readIfPresent(file: string): string | undefined {
    try {
        return fs.readFileSync(file, "utf8");
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
            throw error;
        }
    }
}

function writeAtomically(file: string, content: string): void {
    const dir = path.dirname(file);
    fs.mkdirSync(dir, { recursive: true });
    const temporary = path.join(dir, `.${path.basename(file)}.${randomUUID()}.tmp`);
    try {
        fs.writeFileSync(temporary, content, { flag: "wx" });
        fs.renameSync(temporary, file);
    } finally {
        fs.rmSync(temporary, { force: true });
    }
}

export function writeRpcModule(root: string, methods: readonly MethodExport[]): boolean {
    const rpcPath = path.join(root, RPC_MODULE_PATH);
    const existingRpc = readIfPresent(rpcPath);
    if (existingRpc !== undefined && existingRpc.split(/\r?\n/, 1)[0] !== RPC_MODULE_HEADER) {
        throw new Error(`Cannot generate RPC references: ${rpcPath} already exists and was not generated by HeliumTS. Move or rename that file.`);
    }

    const rpcModule = generateRpcModule(methods, root);
    if (existingRpc === rpcModule) {
        return false;
    }
    writeAtomically(rpcPath, rpcModule);
    return true;
}
